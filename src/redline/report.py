"""Render eval + drift results into a static HTML page (docs/index.html) for GitHub Pages."""

from __future__ import annotations

import html
from pathlib import Path

_CSS = """
body{font-family:system-ui,-apple-system,Segoe UI,sans-serif;max-width:960px;margin:2rem auto;
padding:0 1rem;color:#1f2328;line-height:1.5}
h1{font-size:1.6rem}h2{margin-top:2rem;border-bottom:1px solid #d0d7de;padding-bottom:.3rem}
table{border-collapse:collapse;width:100%;margin:.5rem 0 1rem;font-size:.92rem}
th,td{border:1px solid #d0d7de;padding:.35rem .6rem;text-align:left;vertical-align:top}
th{background:#f6f8fa}.alert{color:#b42318;font-weight:600}.ok{color:#1a7f37;font-weight:600}
code{background:#f6f8fa;padding:0 .25rem;border-radius:4px}.small{color:#57606a;font-size:.85rem}
"""


def _fmt(v) -> str:
    if v is None:
        return "n/a"
    if isinstance(v, float):
        return f"{v:.3f}"
    return html.escape(str(v))


def _metrics_table(results: dict[str, dict]) -> str:
    names = list(results)
    keys = list(next(iter(results.values()))["metrics"])
    head = "<tr><th>metric</th>" + "".join(f"<th>{html.escape(n)}</th>" for n in names) + "</tr>"
    rows = [
        f"<tr><td><code>{k}</code></td>"
        + "".join(f"<td>{_fmt(results[n]['metrics'].get(k))}</td>" for n in names)
        + "</tr>"
        for k in keys
    ]
    return "<table>" + head + "".join(rows) + "</table>"


def _misses(result: dict) -> str:
    rows = [
        c
        for c in result["per_clause"]
        if c["gold_type"] != c["pred_type"] or c["gold_risk"] != c["pred_risk"]
    ]
    body = "".join(
        f"<tr><td>{c['id']}</td><td>{c['gold_type']} / {_fmt(c['gold_risk'])}</td>"
        f"<td>{c['pred_type']} / {_fmt(c['pred_risk'])}</td>"
        f"<td>{html.escape(c['reason'])}</td></tr>"
        for c in rows
    )
    return (
        "<table><tr><th>id</th><th>gold type / risk</th><th>predicted</th><th>reason</th></tr>"
        + body
        + "</table>"
    )


def _drift(name: str, report: dict) -> str:
    cls = "alert" if report["status"] == "ALERT" else "ok"

    def detail(v: dict) -> str:
        return html.escape(", ".join(f"{a}={b}" for a, b in v.items() if a != "alert"))

    rows = "".join(
        f"<tr><td>{k}</td><td>{detail(v)}</td>"
        f"<td class={'alert' if v['alert'] else 'ok'}>{'ALERT' if v['alert'] else 'ok'}</td></tr>"
        for k, v in report["checks"].items()
    )
    return (
        f"<h3>{html.escape(name)}: <span class={cls}>{report['status']}</span></h3>"
        f"<table><tr><th>check</th><th>detail</th><th>status</th></tr>{rows}</table>"
    )


def render(eval_results: dict[str, dict], drift_reports: dict[str, dict], meta: dict) -> str:
    parts = [
        "<!doctype html><html lang=en><meta charset=utf-8>",
        "<meta name=viewport content='width=device-width,initial-scale=1'>",
        f"<title>Contract Redline Copilot: eval report</title><style>{_CSS}</style>",
        "<h1>Contract Redline Copilot: evaluation report</h1>",
        f"<p class=small>Generated by <code>redline report</code>. Backend: "
        f"<code>{html.escape(meta.get('backend', 'offline'))}</code>. Playbook "
        f"<code>{html.escape(meta.get('playbook_version', ''))}</code>. Data: CUAD v1 "
        "(CC BY 4.0, The Atticus Project); labels by the project author, not lawyer-reviewed.</p>",
        "<h2>Metrics</h2>",
        "<p><b>dev</b> = gold set used while writing the playbook checks (optimistic). "
        "<b>blind</b> = labeled after the checks were frozen, never used for tuning.</p>",
        _metrics_table(eval_results),
    ]
    for name, res in eval_results.items():
        parts += [f"<h2>Errors and escalations: {html.escape(name)}</h2>", _misses(res)]
    parts.append("<h2>Drift and data-quality monitor</h2>")
    parts += [_drift(n, r) for n, r in drift_reports.items()]
    parts.append("</html>")
    return "\n".join(parts)


def write_report(path: Path, eval_results: dict, drift_reports: dict, meta: dict) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render(eval_results, drift_reports, meta))
    return path
